export type MessageKey = keyof typeof english
export function t(key: MessageKey, mode: 'en' | 'pseudo' = 'en'): string {
  return mode === 'pseudo' ? pseudoLocalize(english[key]) : english[key]
}

// Complete sentences with named parameters keep word order in the catalogue.
export interface MessageParameters {
  confirmRemove: { name: string }
  confirmArchive: { name: string }
  removeMember: { name: string }
  roleForMember: { name: string }
  replyInThreadCount: { count: string }
  mentionsUnread: { count: string }
  reactionAdd: { emoji: string }
  reactionRemove: { emoji: string }
  newMessageOne: { count: string }
  newMessageOther: { count: string }
}
export function message<K extends keyof MessageParameters>(key: K, values: MessageParameters[K]) {
  return t(key).replace(/\{(\w+)\}/g, (_, name: string) => String((values as Record<string, string>)[name]))
}
