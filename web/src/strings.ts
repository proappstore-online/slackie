export function pseudoLocalize(text: string) {
  return `［${text.replace(/[aeiou]/gi, letter => ({ a: 'á', e: 'ë', i: 'ï', o: 'ô', u: 'ü' })[letter.toLowerCase()]!)}${'~'.repeat(Math.ceil(text.length * .4))}］`
}

